const languageOptions = [
  { value: 'en', label: 'English' },
  { value: 'es', label: 'Español' },
  { value: 'zh', label: '中文' },
  { value: 'de', label: 'Deutsche' },
  { value: 'fr', label: 'Français' },
  { value: 'pt', label: 'Português' },
  { value: 'ru', label: 'Русский' },
  { value: 'tr', label: 'Türk' }
]

function normalizeLanguage(value) {
  const trimmed = String(value || '').trim()
  if (!trimmed) return 'en'
  if (trimmed === 'English') return 'en'
  if (trimmed === 'Español') return 'es'
  if (trimmed === '中文') return 'zh'
  if (trimmed === 'Deutsche' || trimmed === 'Deutsch') return 'de'
  if (trimmed === 'Français') return 'fr'
  if (trimmed === 'Português') return 'pt'
  if (trimmed === 'Русский') return 'ru'
  if (trimmed === 'Türk' || trimmed === 'Türkçe') return 'tr'
  if (trimmed === 'Hindi' || trimmed === 'हिन्दी') return 'en'
  if (translations[trimmed]) return trimmed
  return 'en'
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const stored = localStorage.getItem(LANGUAGE_KEY)
    return normalizeLanguage(stored)
  })

  useEffect(() => {
    localStorage.setItem(LANGUAGE_KEY, language)
    document.documentElement.setAttribute('lang', language)
  }, [language])

  const t = useCallback((key) => {
    return translations[language]?.[key] || key
  }, [language])

  const value = useMemo(() => ({
    language,
    setLanguage,
    languageOptions,
    t
  }), [language, t])

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  )
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) {
    throw new Error('useLanguage must be used within LanguageProvider')
  }
  return context
}
